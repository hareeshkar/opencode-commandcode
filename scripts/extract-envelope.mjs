#!/usr/bin/env node
/**
 * Envelope extractor — finds the request shape the Command Code CLI itself uses.
 *
 * WHY
 * ---
 * Two complementary sources reveal the /alpha/generate contract:
 *
 *   1. scripts/probe-schema.mjs  (network, authoritative)
 *      The repair loop discovers every REQUIRED field, because Zod rejects a
 *      body that omits one. But it cannot see OPTIONAL fields: the server
 *      ignores unknown keys, so there is no error to read.
 *
 *   2. THIS SCRIPT (static, from the vendor's own client)
 *      The CLI bundle contains the literal body it POSTs on every turn. That
 *      literal names the optional fields too (`taste`, `skills`, `promptCache`,
 *      `mode`, `reasoning_effort`, ...), which the network probe can then
 *      confirm and type.
 *
 * Together they give full coverage with no hand-written field lists.
 *
 * HOW IT WORKS
 * ------------
 * 1. Locate the route constant for "/alpha/generate" in the minified bundle.
 * 2. Find every call site that passes `route:<thatConstant>`.
 * 3. Walk the `body:` object literal at that call site with balanced-brace
 *    matching (regex cannot handle nesting).
 * 4. Emit the set of key paths, both literal (`memory:`) and computed
 *    (`mode: t.mode`) — a computed key still proves the field exists.
 *
 * Usage: node scripts/extract-envelope.mjs [--out envelope.generated.json]
 */

import { readFileSync, existsSync } from "node:fs"
import os from "node:os"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { argOut, writeJson } from "./safe-io.mjs"

const HERE = path.dirname(fileURLToPath(import.meta.url))
const REPO = path.resolve(HERE, "..")
const JSON_ONLY = process.argv.includes("--json-only")
const OUT = argOut("--out", path.join(REPO, "envelope.generated.json"))
const say = (...a) => { if (!JSON_ONLY) process.stderr.write(a.join(" ") + "\n") }

const BUNDLE =
  process.argv[2] ||
  path.join(os.homedir(), ".local/lib/node_modules/command-code/dist/cli.mjs")

if (!existsSync(BUNDLE)) {
  say(`bundle not found: ${BUNDLE}`)
  process.exit(2)
}
const src = readFileSync(BUNDLE, "utf8")

/** Read the identifier bound to a string literal, e.g. `Hk="/alpha/generate"`. */
function findRouteConst(route) {
  const re = new RegExp(`([A-Za-z_$][\\w$]*)\\s*=\\s*"${route.replace(/[/]/g, "\\/")}"`)
  const m = src.match(re)
  return m ? m[1] : null
}

const routeConst = findRouteConst("/alpha/generate")
if (!routeConst) {
  say('could not find the "/alpha/generate" route constant — CLI layout may have changed')
  process.exit(3)
}
say(`route constant: ${routeConst}`)

/** Balanced-brace slice starting at the '{' at or after `from`. */
function sliceObject(text, from) {
  let i = text.indexOf("{", from)
  if (i === -1) return null
  let depth = 0, quote = null, esc = false
  for (let j = i; j < text.length; j++) {
    const c = text[j]
    if (quote) {
      if (esc) esc = false
      else if (c === "\\") esc = true
      else if (c === quote) quote = null
      continue
    }
    if (c === '"' || c === "'" || c === "`") { quote = c; continue }
    if (c === "{") depth++
    else if (c === "}") { depth--; if (depth === 0) return { text: text.slice(i, j + 1), start: i, end: j + 1 } }
  }
  return null
}

/** Collect key paths from an object literal, descending into nested objects. */
function keysOf(literal, prefix = "") {
  const found = new Set()
  // literal keys:  word:            computed keys: expr.word:   shorthand: word,
  const re = /(?:^|[{,])\s*(?:([A-Za-z_$][\w$]*)|([A-Za-z_$][\w$]*\.[A-Za-z_$][\w$]*))\s*[:,]/g
  let m
  while ((m = re.exec(literal))) {
    const key = m[1] || m[2].split(".").pop()
    if (!key) continue
    found.add(prefix + key)
  }
  return found
}

// Find every `route:<routeConst>` call site and harvest the body literal.
const sites = []
let idx = 0
let hit
const siteRe = new RegExp(`route:\\s*${routeConst.replace(/\$/g, "\\$")}`, "g")
while ((hit = siteRe.exec(src))) {
  const win = src.slice(hit.index, hit.index + 1200)
  const bodyAt = win.indexOf("body:")
  if (bodyAt === -1) continue
  const obj = sliceObject(win, bodyAt)
  if (!obj) continue
  sites.push(obj)
  idx++
}
say(`found ${idx} request site(s) carrying route:${routeConst}`)

const allKeys = new Set()
for (const s of sites) {
  for (const k of keysOf(s.text)) allKeys.add(k)
}

// The `params:` sub-object is nested; harvest it separately for clarity.
const paramKeys = new Set()
for (const s of sites) {
  const pAt = s.text.indexOf("params:")
  if (pAt === -1) continue
  const inner = sliceObject(s.text, pAt)
  if (!inner) continue
  for (const k of keysOf(inner.text)) paramKeys.add(k)
}

const envelope = {
  $comment:
    "GENERATED by scripts/extract-envelope.mjs from the Command Code CLI bundle. " +
    "Static evidence of the optional fields the network probe cannot see.",
  generatedAt: new Date().toISOString(),
  bundle: BUNDLE,
  bundleBytes: src.length,
  route: "/alpha/generate",
  routeConstant: routeConst,
  requestSites: sites.length,
  topLevelKeys: [...allKeys].filter((k) => !k.includes(".")).sort(),
  paramKeys: [...paramKeys].sort(),
  allKeys: [...allKeys].sort(),
}

writeJson(OUT, envelope)
say(`wrote ${path.relative(REPO, OUT)}`)
say(`  top-level keys : ${envelope.topLevelKeys.join(", ")}`)
say(`  params keys   : ${envelope.paramKeys.join(", ")}`)
